const sortedAppPhrases = Object.entries(appPhrases).sort((a, b) => b[0].length - a[0].length);

const dictionaries: Record<Lang, Record<string, string>> = {
  it: { ...it, ...Object.fromEntries(Object.keys(appLabels).map((key) => [key, key])) },
  en: { ...en, ...appLabels },
};

type I18nContextValue = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  toggle: () => void;
  t: (key: string) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "it" || stored === "en") setLangState(stored);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
    window.localStorage.setItem(STORAGE_KEY, lang);
  }, [lang]);

  const setLang = useCallback((next: Lang) => setLangState(next), []);
  const toggle = useCallback(() => setLangState((v) => (v === "it" ? "en" : "it")), []);
  const t = useCallback(
    (key: string) => {
      const resolved = dictionaries[lang][key] ?? dictionaries.it[key] ?? key;
      if (lang === "it") return resolved;
      return sortedAppPhrases.reduce(
        (value, [from, to]) => (value.includes(from) ? value.split(from).join(to) : value),
        resolved,
      );
    },
    [lang],
  );

  const value = useMemo<I18nContextValue>(() => ({ lang, setLang, toggle, t }), [lang, setLang, toggle, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}

export function LanguageSwitch({ className }: { className?: string }) {
  const { lang, setLang } = useI18n();
  return (
    <div
      className={`inline-flex items-center rounded-full border border-line bg-white/70 p-0.5 text-[11.5px] ${className ?? ""}`}
      role="group"
      aria-label="Language"
    >
      {(["it", "en"] as const).map((code) => (
        <button
          key={code}
          type="button"
          onClick={() => setLang(code)}
          aria-pressed={lang === code}
          className={`rounded-full px-2 py-1 font-mono uppercase tracking-[0.1em] transition-colors ${
            lang === code ? "bg-forest text-paper" : "text-muted hover:text-ink"
          }`}
        >
          {code}
        </button>
      ))}
    </div>
  );
}
